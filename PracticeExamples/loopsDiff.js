//for loop - when we know the number of iterations
// ex 
for(let i=1;i<=5;i++){
    console.log(i);
}

//while loop - when we don't know the number of iterations in advance
let j =1;
while(j<=5){
    console.log(j);
    j++;
}

//do-while - runs at least one time even if the condition is false
let k=1
do{
    console.log(k);
    k++;
}
while(k<=5);