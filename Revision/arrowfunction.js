//arrow function is a short hand for writing a function

//single line arrow function
let aFun = num => num*num;
console.log(aFun(5));

//using return with 2 parameters and paranthesis
let sum = (a,b) => {
    return a + b;
}
console.log(sum(10,20));

//one parameter
let name = (name)=>{
    return name;
}
console.log(name("neha mishra"));

